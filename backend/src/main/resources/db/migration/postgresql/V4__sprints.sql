-- Phase 5b: sprints, plus story points, labels and sprint membership on issues.
CREATE TABLE sprints (
    id                  BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    company_id          BIGINT NOT NULL,
    project_id          BIGINT NOT NULL REFERENCES projects (id),
    name                VARCHAR(100) NOT NULL,
    goal                VARCHAR(500),
    status              VARCHAR(20) NOT NULL DEFAULT 'PLANNED',
    start_date          DATE,
    end_date            DATE,
    started_at          TIMESTAMP(6),
    completed_at        TIMESTAMP(6),
    completed_count     INTEGER,
    carried_over_count  INTEGER,
    created_at          TIMESTAMP(6) NOT NULL,
    updated_at          TIMESTAMP(6) NOT NULL
);
CREATE INDEX idx_sprints_company_project ON sprints (company_id, project_id);

ALTER TABLE issues ADD COLUMN sprint_id BIGINT REFERENCES sprints (id);
ALTER TABLE issues ADD COLUMN story_points INTEGER;
ALTER TABLE issues ADD COLUMN labels VARCHAR(500);
CREATE INDEX idx_issues_company_sprint ON issues (company_id, sprint_id);
