-- Phase 7: company knowledge base (RAG).
CREATE TABLE kb_documents (
    id                 BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    company_id         BIGINT NOT NULL,
    title              VARCHAR(200) NOT NULL,
    file_name          VARCHAR(255),
    audience           VARCHAR(20) NOT NULL,
    status             VARCHAR(20) NOT NULL,
    error_message      VARCHAR(300),
    content_hash       VARCHAR(64) NOT NULL,
    char_count         INTEGER NOT NULL,
    chunk_count        INTEGER NOT NULL,
    embedding_model    VARCHAR(80),
    uploaded_by_emp_id INTEGER,
    created_at         TIMESTAMP(6) NOT NULL,
    updated_at         TIMESTAMP(6) NOT NULL
);
CREATE INDEX idx_kb_documents_company ON kb_documents (company_id, created_at);
CREATE INDEX idx_kb_documents_hash ON kb_documents (company_id, content_hash);

CREATE TABLE kb_chunks (
    id              BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    company_id      BIGINT NOT NULL,
    document_id     BIGINT NOT NULL,
    chunk_index     INTEGER NOT NULL,
    content         TEXT NOT NULL,
    embedding_json  TEXT,
    embedding_model VARCHAR(80)
);
CREATE INDEX idx_kb_chunks_document ON kb_chunks (document_id, chunk_index);
CREATE INDEX idx_kb_chunks_company ON kb_chunks (company_id);

-- pgvector is optional: if the extension cannot be created (not installed, or no permission) the app falls back to
-- the portable scan search over embedding_json. If it can, vectors are also stored in a native column with an HNSW index.
DO $$
BEGIN
    BEGIN
        CREATE EXTENSION IF NOT EXISTS vector;
    EXCEPTION WHEN OTHERS THEN
        RAISE NOTICE 'pgvector not available (%): using scan search', SQLERRM;
    END;
    IF EXISTS (SELECT 1 FROM pg_extension WHERE extname = 'vector') THEN
        EXECUTE 'ALTER TABLE kb_chunks ADD COLUMN embedding vector(768)';
        EXECUTE 'CREATE INDEX idx_kb_chunks_embedding ON kb_chunks USING hnsw (embedding vector_cosine_ops)';
    END IF;
END
$$;
