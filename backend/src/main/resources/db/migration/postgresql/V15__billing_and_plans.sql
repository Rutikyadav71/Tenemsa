-- Plans, subscriptions and billing events (Razorpay), plus a per-company monthly AI token override. See docs/billing.md.
ALTER TABLE companies ADD COLUMN ai_monthly_tokens BIGINT;

CREATE TABLE plans (
    code               VARCHAR(30) PRIMARY KEY,
    name               VARCHAR(60)  NOT NULL,
    description        VARCHAR(250),
    price_paise        INTEGER      NOT NULL DEFAULT 0,
    max_users          INTEGER,
    monthly_ai_tokens  BIGINT,
    max_connections    INTEGER,
    contact_only       BOOLEAN      NOT NULL DEFAULT FALSE,
    razorpay_plan_id   VARCHAR(60),
    sort_order         INTEGER      NOT NULL DEFAULT 0,
    active             BOOLEAN      NOT NULL DEFAULT TRUE
);

