CREATE TABLE subscriptions (
    id                        BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    company_id                BIGINT       NOT NULL,
    plan_code                 VARCHAR(30)  NOT NULL,
    razorpay_subscription_id  VARCHAR(60)  NOT NULL UNIQUE,
    status                    VARCHAR(20)  NOT NULL,
    current_start             TIMESTAMP(6),
    current_end               TIMESTAMP(6),
    paid_count                INTEGER      NOT NULL DEFAULT 0,
    cancel_at_period_end      BOOLEAN      NOT NULL DEFAULT FALSE,
    created_at                TIMESTAMP(6) NOT NULL,
    updated_at                TIMESTAMP(6) NOT NULL
);
CREATE INDEX idx_subscriptions_company ON subscriptions (company_id, status);

CREATE TABLE billing_events (
    id                   BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    company_id           BIGINT,
    razorpay_event_id    VARCHAR(80) UNIQUE,
    event_type           VARCHAR(60)  NOT NULL,
    razorpay_payment_id  VARCHAR(60),
    amount_paise         BIGINT,
    status               VARCHAR(20),
    created_at           TIMESTAMP(6) NOT NULL
);
CREATE INDEX idx_billing_events_company ON billing_events (company_id, created_at);
